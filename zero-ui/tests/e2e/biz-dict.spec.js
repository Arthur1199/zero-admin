import { test, expect } from '@playwright/test'
import { mockBizDict } from './biz-dict-mock'

const root = '/reportSystem/bizDict'
const groupRow = (page, code) => page.locator('.biz-dict-page > .el-table .el-table__row').filter({ has: page.getByText(code, { exact: true }) })
const itemRow = (page, name) => page.locator('.dict-item-table .el-table__row').filter({ has: page.getByText(name, { exact: true }) })
const dialog = page => page.locator('.el-dialog:visible')
const submit = page => dialog(page).getByRole('button', { name: /确\s*定/ }).click()

async function confirm(page) {
  await page.locator('.el-message-box:visible').getByRole('button', { name: '确定', exact: true }).click()
}
async function expand(page, code) {
  await groupRow(page, code).locator('.el-table__expand-icon').click()
  await expect(page.locator('.dict-item-table').first()).toBeVisible()
}
async function fillGroup(page, code, name) {
  await dialog(page).getByPlaceholder('请输入字典组编码', { exact: true }).fill(code)
  await dialog(page).getByPlaceholder('请输入字典组名称', { exact: true }).fill(name)
}
async function fillItem(page) {
  await dialog(page).getByPlaceholder('请输入字典编码', { exact: true }).fill('browser-item')
  await dialog(page).getByPlaceholder('请输入字典名称', { exact: true }).fill('浏览器字典项')
  await dialog(page).getByPlaceholder('请输入字典值', { exact: true }).fill('value-a')
}

test('字典查询使用全量options，删除标志、日期和重置保持参数契约', async ({ page }) => {
  const state = await mockBizDict(page)
  await page.goto(root)
  await page.getByRole('combobox', { name: '字典组编码', exact: true }).click()
  await expect(page.getByRole('option', { name: 'deleted（已删除组）', exact: true })).toBeVisible()
  await page.getByRole('option', { name: 'deleted（已删除组）', exact: true }).click()
  await page.getByText('请选择状态', { exact: true }).click()
  await page.getByRole('option', { name: '停用', exact: true }).click()
  await page.getByText('请选择删除标志', { exact: true }).click()
  await page.getByRole('option', { name: '已删除', exact: true }).click()
  await page.getByPlaceholder('开始日期', { exact: true }).fill('2026-01-01')
  await page.getByPlaceholder('结束日期', { exact: true }).fill('2026-01-31')
  await page.getByPlaceholder('结束日期', { exact: true }).press('Enter')
  await page.getByRole('button', { name: '搜索', exact: true }).click()
  await expect(groupRow(page, 'deleted')).toBeVisible()
  await expect.poll(() => state.requests.filter(request => request.path.endsWith('/group/list')).at(-1).query).toMatchObject({
    groupCode: 'deleted', status: '0', delFlag: '1', pageNum: '1', pageSize: '10', beginTime: '2026-01-01', endTime: '2026-01-31'
  })
  await page.getByRole('button', { name: '重置', exact: true }).click()
  await expect(groupRow(page, 'active')).toBeVisible()
  await expect.poll(() => state.requests.filter(request => request.path.endsWith('/group/list')).at(-1).query).toEqual({ pageNum: '1', pageSize: '10' })
})

test('字典组校验、新增、修改、删除和恢复刷新列表与options', async ({ page }) => {
  const state = await mockBizDict(page)
  await page.goto(root)
  await page.getByRole('button', { name: '新增字典组', exact: true }).click()
  await submit(page)
  await expect(dialog(page).getByText('字典组编码不能为空', { exact: true })).toBeVisible()
  expect(state.requests.some(request => request.method === 'POST')).toBe(false)
  await fillGroup(page, 'browser-group', '浏览器字典组')
  await dialog(page).getByText('停用', { exact: true }).click()
  await expect(dialog(page).getByRole('radio', { name: '停用', exact: true })).toBeChecked()
  await submit(page)
  await expect(dialog(page)).not.toBeVisible()
  await expect(groupRow(page, 'browser-group')).toBeVisible()
  expect(state.requests.find(request => request.method === 'POST').data).toMatchObject({ groupCode: 'browser-group', groupName: '浏览器字典组', status: '0' })
  await groupRow(page, 'browser-group').getByRole('button', { name: '修改', exact: true }).click()
  await expect(dialog(page).getByPlaceholder('请输入字典组名称')).toHaveValue('浏览器字典组')
  await dialog(page).getByPlaceholder('请输入字典组名称').fill('修改后的字典组')
  await submit(page)
  await expect(groupRow(page, 'browser-group')).toContainText('修改后的字典组')
  const saved = state.requests.find(request => request.method === 'PUT' && request.path === root + '/group')
  expect(saved.data.id).toBe(3)
  await groupRow(page, 'browser-group').getByRole('button', { name: '删除', exact: true }).click()
  await confirm(page)
  await expect(groupRow(page, 'browser-group').getByRole('button', { name: '恢复', exact: true })).toBeVisible()
  await expect(groupRow(page, 'browser-group').getByRole('button', { name: '修改', exact: true })).toBeDisabled()
  await groupRow(page, 'browser-group').getByRole('button', { name: '恢复', exact: true }).click()
  await confirm(page)
  await expect(groupRow(page, 'browser-group').getByRole('button', { name: '删除', exact: true })).toBeVisible()
  expect(state.requests.some(request => request.path === root + '/group/3' && request.method === 'DELETE')).toBe(true)
  expect(state.requests.some(request => request.path === root + '/group/restore/3' && request.method === 'PUT')).toBe(true)
  expect(state.requests.filter(request => request.path.endsWith('/group/options')).length).toBe(5)
})

test('字典项所属组回显、数字排序、新增修改删除恢复保持字段类型', async ({ page }) => {
  const state = await mockBizDict(page)
  await page.goto(root)
  await expand(page, 'active')
  await page.getByRole('button', { name: '新增字典项', exact: true }).click()
  await expect(dialog(page).locator('.el-input.is-disabled input')).toHaveValue('正常组（active）')
  await fillItem(page)
  await dialog(page).getByRole('spinbutton').fill('7')
  await dialog(page).getByRole('spinbutton').press('Tab')
  await dialog(page).getByPlaceholder('请输入拓展配置JSON').fill('{"mode":"test"}')
  await submit(page)
  await expect(itemRow(page, '浏览器字典项')).toBeVisible()
  expect(state.requests.find(request => request.path === root + '/item' && request.method === 'POST').data).toMatchObject({ groupId: 1, itemSort: 7, status: '1', extraJson: '{"mode":"test"}' })
  await itemRow(page, '浏览器字典项').getByRole('button', { name: '修改', exact: true }).click()
  await dialog(page).getByPlaceholder('请输入字典值', { exact: true }).fill('value-b')
  await submit(page)
  await expect(itemRow(page, '浏览器字典项')).toContainText('value-b')
  await itemRow(page, '浏览器字典项').getByRole('button', { name: '删除', exact: true }).click()
  await confirm(page)
  await expect(itemRow(page, '浏览器字典项').getByRole('button', { name: '恢复', exact: true })).toBeVisible()
  await itemRow(page, '浏览器字典项').getByRole('button', { name: '恢复', exact: true }).click()
  await confirm(page)
  await expect(itemRow(page, '浏览器字典项').getByRole('button', { name: '删除', exact: true })).toBeVisible()
  expect(state.requests.some(request => request.path === root + '/item/203' && request.method === 'DELETE')).toBe(true)
  expect(state.requests.some(request => request.path === root + '/item/restore/203' && request.method === 'PUT')).toBe(true)
})

test('父组已删除时子项按钮禁用；删除恢复共用权限，列表账号隐藏写入口', async ({ page, context }) => {
  await mockBizDict(page)
  await page.goto(root)
  await expand(page, 'deleted')
  await expect(groupRow(page, 'deleted').getByRole('button', { name: '新增项', exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: '新增字典项', exact: true })).toBeDisabled()
  await expect(itemRow(page, '父级删除子项').getByRole('button', { name: '删除', exact: true })).toBeDisabled()
  await expect(itemRow(page, '父级删除已删子项').getByRole('button', { name: '恢复', exact: true })).toBeDisabled()
  const readOnly = await context.newPage()
  await mockBizDict(readOnly, { roles: ['common'], permissions: ['reportSystem:bizDict:list'] })
  await readOnly.goto(root)
  await expect(groupRow(readOnly, 'active')).toBeVisible()
  await expect(readOnly.getByRole('button', { name: /新增字典组|新增项|修改|删除|恢复/ })).toHaveCount(0)
  await expand(readOnly, 'active')
  await expect(readOnly.getByRole('button', { name: /新增字典项|修改|删除|恢复/ })).toHaveCount(0)
  await readOnly.close()
  const removeOnly = await context.newPage()
  await mockBizDict(removeOnly, { roles: ['common'], permissions: ['reportSystem:bizDict:list', 'reportSystem:bizDict:remove'] })
  await removeOnly.goto(root)
  await expect(groupRow(removeOnly, 'active').getByRole('button', { name: '删除', exact: true })).toBeVisible()
  await expect(groupRow(removeOnly, 'deleted').getByRole('button', { name: '恢复', exact: true })).toBeVisible()
  await expect(removeOnly.getByRole('button', { name: /新增字典组|新增项|修改/ })).toHaveCount(0)
  await expand(removeOnly, 'active')
  await expect(itemRow(removeOnly, '正常项').getByRole('button', { name: '删除', exact: true })).toBeVisible()
  await expect(itemRow(removeOnly, '已删除项').getByRole('button', { name: '恢复', exact: true })).toBeVisible()
  await removeOnly.close()
})

for (const kind of ['group', 'item']) {
  test(kind + '详情及提交失败不产生未处理异常，表单保留且能重试', async ({ page }) => {
    const errors = []; page.on('pageerror', error => errors.push(error.message))
    const state = await mockBizDict(page)
    const id = kind === 'group' ? 1 : 101
    state.failures.set('GET ' + root + '/' + kind + '/' + id, 1)
    await page.goto(root)
    if (kind === 'item') await expand(page, 'active')
    const row = kind === 'group' ? groupRow(page, 'active') : itemRow(page, '正常项')
    await row.getByRole('button', { name: '修改', exact: true }).click()
    await expect(page.getByText('模拟字典请求失败', { exact: true })).toBeVisible()
    await expect(dialog(page)).not.toBeVisible()
    await row.getByRole('button', { name: '修改', exact: true }).click()
    await expect(dialog(page)).toBeVisible()
    state.failures.set('PUT ' + root + '/' + kind, 1)
    await dialog(page).getByPlaceholder(kind === 'group' ? '请输入字典组名称' : '请输入字典名称', { exact: true }).fill('失败后保留的字段')
    await submit(page)
    await expect(dialog(page)).toBeVisible()
    await expect(dialog(page).getByPlaceholder(kind === 'group' ? '请输入字典组名称' : '请输入字典名称', { exact: true })).toHaveValue('失败后保留的字段')
    // 防重复拦截是一秒窗口，通过公开字段修改构成真实重试，不注入请求缓存。
    await dialog(page).getByPlaceholder('请输入备注', { exact: true }).fill('重试')
    await submit(page)
    await expect(dialog(page)).not.toBeVisible()
    expect(errors).toEqual([])
  })
}
